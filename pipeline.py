DEFAULT_HP = {"CatBoost": {"iterations": 500, "learning_rate": 0.1, "depth": 6, "l2_leaf_reg": 3},
              "RandomForest": {"n_estimators": 200, "max_depth": 20,
                               "min_samples_split": 5, "max_features": "sqrt"}}
